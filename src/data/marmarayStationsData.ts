export function getMarmarayStationDetail(rawName: string): StationDetail | null {
  if (!rawName) return null;
  const clean = rawName
    .replace(/\s+Station(\s*\([A-Za-z0-9]+\))?$/i, '')
    .replace(/\s+İstasyonu(\s*\([A-Za-z0-9]+\))?$/i, '')
    .replace(/\s*\([A-Za-z0-9]+\)$/i, '')
    .trim()
    .toLowerCase();

  if (MARMARAY_STATIONS_DATA[clean]) {
    return MARMARAY_STATIONS_DATA[clean];
  }

  const normalize = (s: string) =>
    s
      .toLowerCase()
      .replace(/i̇/g, 'i')
      .replace(/ı/g, 'i')
      .replace(/ö/g, 'o')
      .replace(/ü/g, 'u')
      .replace(/ş/g, 's')
      .replace(/ç/g, 'c')
      .replace(/ğ/g, 'g');

  const normalizedClean = normalize(clean);

  for (const [key, val] of Object.entries(MARMARAY_STATIONS_DATA)) {
    const normalizedKey = normalize(key);
    if (
      normalizedClean === normalizedKey ||
      normalizedClean.includes(normalizedKey) ||
      normalizedKey.includes(normalizedClean)
    ) {
      return val;
    }
  }

  // Fallback keyword checks
  if (normalizedClean.includes('halkali') || normalizedClean.includes('halkalı')) return MARMARAY_STATIONS_DATA['halkalı'];
  if (normalizedClean.includes('mustafa kemal')) return MARMARAY_STATIONS_DATA['mustafa kemal'];
  if (normalizedClean.includes('kucukcekmece') || normalizedClean.includes('küçükçekmece')) return MARMARAY_STATIONS_DATA['küçükçekmece'];
  if (normalizedClean.includes('florya akvaryum')) return MARMARAY_STATIONS_DATA['florya akvaryum'];
  if (normalizedClean.includes('florya')) return MARMARAY_STATIONS_DATA['florya'];
  if (normalizedClean.includes('yesilkoy') || normalizedClean.includes('yeşilköy')) return MARMARAY_STATIONS_DATA['yeşilköy'];
  if (normalizedClean.includes('yesilyurt') || normalizedClean.includes('yeşilyurt')) return MARMARAY_STATIONS_DATA['yeşilyurt'];
  if (normalizedClean.includes('atakoy') || normalizedClean.includes('ataköy')) return MARMARAY_STATIONS_DATA['ataköy'];
  if (normalizedClean.includes('bakirkoy') || normalizedClean.includes('bakırköy')) return MARMARAY_STATIONS_DATA['bakırköy'];
  if (normalizedClean.includes('yenimahalle')) return MARMARAY_STATIONS_DATA['yenimahalle'];
  if (normalizedClean.includes('zeytinburnu') || normalizedClean.includes('fisekhane')) return MARMARAY_STATIONS_DATA['zeytinburnu-fişekhane'];
  if (normalizedClean.includes('kazlicesme') || normalizedClean.includes('kazlıçeşme')) return MARMARAY_STATIONS_DATA['kazlıçeşme'];
  if (normalizedClean.includes('yenikapi') || normalizedClean.includes('yenikapı')) return MARMARAY_STATIONS_DATA['yenikapı'];
  if (normalizedClean.includes('sirkeci')) return MARMARAY_STATIONS_DATA['sirkeci'];
  if (normalizedClean.includes('uskudar') || normalizedClean.includes('üsküdar')) return MARMARAY_STATIONS_DATA['üsküdar'];
  if (normalizedClean.includes('ayrilik') || normalizedClean.includes('ayrılık')) return MARMARAY_STATIONS_DATA['ayrılık çeşmesi'];
  if (normalizedClean.includes('sogutlucesme') || normalizedClean.includes('söğütlüçeşme')) return MARMARAY_STATIONS_DATA['söğütlüçeşme'];
  if (normalizedClean.includes('feneryolu')) return MARMARAY_STATIONS_DATA['feneryolu'];
  if (normalizedClean.includes('goztepe') || normalizedClean.includes('göztepe')) return MARMARAY_STATIONS_DATA['göztepe'];
  if (normalizedClean.includes('erenkoy') || normalizedClean.includes('erenköy')) return MARMARAY_STATIONS_DATA['erenköy'];
  if (normalizedClean.includes('suadiye')) return MARMARAY_STATIONS_DATA['suadiye'];
  if (normalizedClean.includes('bostanci') || normalizedClean.includes('bostancı')) return MARMARAY_STATIONS_DATA['bostancı'];
  if (normalizedClean.includes('kucukyali') || normalizedClean.includes('küçükyalı')) return MARMARAY_STATIONS_DATA['küçükyalı'];
  if (normalizedClean.includes('idealtepe')) return MARMARAY_STATIONS_DATA['idealtepe'];
  if (normalizedClean.includes('sureyya') || normalizedClean.includes('süreyya')) return MARMARAY_STATIONS_DATA['süreyya plajı'];
  if (normalizedClean.includes('maltepe')) return MARMARAY_STATIONS_DATA['maltepe'];
  if (normalizedClean.includes('cevizli')) return MARMARAY_STATIONS_DATA['cevizli'];
  if (normalizedClean.includes('atalar')) return MARMARAY_STATIONS_DATA['atalar'];
  if (normalizedClean.includes('basak') || normalizedClean.includes('başak')) return MARMARAY_STATIONS_DATA['başak'];
  if (normalizedClean.includes('kartal')) return MARMARAY_STATIONS_DATA['kartal'];
  if (normalizedClean.includes('yunus')) return MARMARAY_STATIONS_DATA['yunus'];
  if (normalizedClean.includes('pendik')) return MARMARAY_STATIONS_DATA['pendik'];
  if (normalizedClean.includes('kaynarca')) return MARMARAY_STATIONS_DATA['kaynarca'];
  if (normalizedClean.includes('tersane')) return MARMARAY_STATIONS_DATA['tersane'];
  if (normalizedClean.includes('guzelyali') || normalizedClean.includes('güzelyalı')) return MARMARAY_STATIONS_DATA['güzelyalı'];
  if (normalizedClean.includes('aydintepe') || normalizedClean.includes('aydıntepe')) return MARMARAY_STATIONS_DATA['aydıntepe'];
  if (normalizedClean.includes('icmeler') || normalizedClean.includes('içmeler')) return MARMARAY_STATIONS_DATA['içmeler'];
  if (normalizedClean.includes('tuzla')) return MARMARAY_STATIONS_DATA['tuzla'];
  if (normalizedClean.includes('cayirova') || normalizedClean.includes('çayırova')) return MARMARAY_STATIONS_DATA['çayırova'];
  if (normalizedClean.includes('gtu') || normalizedClean.includes('gtü') || normalizedClean.includes('fatih')) return MARMARAY_STATIONS_DATA['fatih'];
  if (normalizedClean.includes('osmangazi')) return MARMARAY_STATIONS_DATA['osmangazi'];
  if (normalizedClean.includes('darica') || normalizedClean.includes('darıca')) return MARMARAY_STATIONS_DATA['darıca'];
  if (normalizedClean.includes('gebze')) return MARMARAY_STATIONS_DATA['gebze'];

  return null;
}
